"""Try several ways of chunking and embedding the notes and compare search quality.

Every variant is built in a throw-away index, so your real index is never touched.
Writes the result table to docs/TUNING.md. Run: bash scripts/tune.sh
"""
import dataclasses
import shutil
import sys
import tempfile
import time
from itertools import product
from pathlib import Path

from jarvis.config import ROOT, load_config
from jarvis.llm import LLMError, OllamaClient
from jarvis.memory.evaluate import load_cases, run_cases, summarize
from jarvis.memory.ingest import ingest
from jarvis.memory.store import StoreError

cfg = load_config()
cases, _off = load_cases(cfg.notes_dir / "eval-cases.toml")
llm = OllamaClient(cfg.ollama_url, cfg.model, cfg.timeout_seconds, cfg.embed_model)
NOMIC = ("search_document: ", "search_query: ")

variants = []  # (label, overrides)
for chars, header, task in product((400, 800, 1200), (True, False), (False, True)):
    label = f"{chars} chars, header {'yes' if header else 'no'}, task prefix {'yes' if task else 'no'}"
    variants.append((label, dict(
        memory_chunk_chars=chars, memory_note_header=header,
        memory_doc_prefix=NOMIC[0] if task else "", memory_query_prefix=NOMIC[1] if task else "")))

tmp_root = Path(tempfile.mkdtemp(prefix="tune-", dir=ROOT / ".tools"))
rows = []
try:
    for i, (label, over) in enumerate(variants):
        c = dataclasses.replace(cfg, index_dir=tmp_root / f"v{i}", **over)
        start = time.time()
        res = ingest(c, llm.embed)
        s = summarize(run_cases(c, llm.embed, cases))
        rows.append((label, over == dict(
            memory_chunk_chars=cfg.memory_chunk_chars, memory_note_header=cfg.memory_note_header,
            memory_doc_prefix=cfg.memory_doc_prefix, memory_query_prefix=cfg.memory_query_prefix), res.chunks, s))
        print(f"[{i + 1}/{len(variants)}] {label}: top-1 {s.top1}/{s.n}, hit@3 {s.hit3}/{s.n}, MRR {s.mrr:.3f} "
              f"({time.time() - start:.0f}s)", flush=True)
except (LLMError, StoreError) as exc:
    sys.exit(f"tuning failed: {exc}")
finally:
    shutil.rmtree(tmp_root, ignore_errors=True)

best = max(rows, key=lambda r: (r[3].mrr, r[3].top1))
n = rows[0][3].n
lines = [
    "# Search tuning (generated by scripts/tune.py)",
    "",
    f"{n} test questions. top-1 = right note ranked first. hit@3 = right note in the top 3. "
    "hit@5 = in the top 5. MRR = average of 1/rank (1.0 is perfect).",
    "",
    "| Variant | Chunks | top-1 | hit@3 | hit@5 | MRR |",
    "| --- | --- | --- | --- | --- | --- |",
]
for row in rows:
    label, is_current, chunks, s = row
    mark = " (current config)" if is_current else ""
    mark += " (best)" if row is best else ""
    lines.append(f"| {label}{mark} | {chunks} | {s.top1} | {s.hit3} | {s.hit5} | {s.mrr:.3f} |")
lines += ["", f"With {n} questions, one question is {100 / n:.0f} points. A gap of one or two questions is noise, "
          "not a result. Change the config only for a clear gap, then run scripts/ingest.sh again."]
(ROOT / "docs" / "TUNING.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("\n".join(lines[4:]))
print("\nwrote docs/TUNING.md")
