#!/usr/bin/env bash
# One-time setup. Installs uv, Python, Ollama, project deps and the model, all inside this repo.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/env.sh"
cd "$ROOT"
mkdir -p .tools/bin .tools/ollama models/ollama models/hf

echo "==> uv (into .tools/bin)"
if [ ! -x .tools/bin/uv ]; then
  curl -LsSf https://astral.sh/uv/install.sh | UV_INSTALL_DIR="$ROOT/.tools/bin" UV_NO_MODIFY_PATH=1 sh
fi
uv --version

echo "==> Python + dependencies (into .venv and .tools/python)"
uv sync --python 3.12

echo "==> Ollama binary (into .tools/ollama)"
if [ ! -x .tools/ollama/ollama ]; then
  curl -fL -o .tools/ollama.tgz "https://github.com/ollama/ollama/releases/latest/download/ollama-darwin.tgz"
  tar -xzf .tools/ollama.tgz -C .tools/ollama
  rm -f .tools/ollama.tgz
fi
ollama --version || true

if [ -n "${SKIP_MODELS:-}" ]; then
  echo "==> SKIP_MODELS is set: not starting Ollama, not pulling models (install check only)"
else
  echo "==> Start private Ollama on $OLLAMA_HOST (models stored in models/ollama)"
  bash scripts/ollama-up.sh

  MODEL="$(uv run python -c 'from jarvis.config import load_config; print(load_config().model)')"
  echo "==> Pull model: $MODEL"
  ollama pull "$MODEL"
  EMBED="$(uv run python -c 'from jarvis.config import load_config; print(load_config().embed_model)')"
  echo "==> Pull embedding model: $EMBED"
  ollama pull "$EMBED"

  echo "==> Save model info to models/model-info.txt"
  { echo "# generated by scripts/setup.sh on $(date)"; ollama show "$MODEL"; } > models/model-info.txt || true

  echo "==> Doctor"
  uv run jarvis --doctor
fi
echo "Setup finished. Chat with: scripts/run.sh"
